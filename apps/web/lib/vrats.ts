export function vratSlugs(): string[] {
  return VRATS.map((v) => v.slug);
}

export function getVrat(slug: string): Vrat | undefined {
  return VRATS.find((v) => v.slug === slug);
}

export function vratsByCategory(category: Vrat['category']): Vrat[] {
  return VRATS.filter((v) => v.category === category);
}
